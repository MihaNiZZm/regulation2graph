"""
Морфологические утилиты для генерации имён состояний.

Использует pymorphy3 для:
- Определения рода существительного (объекта)
- Генерации краткого страдательного причастия (пассивный залог)
"""

import pymorphy3

# Singleton для MorphAnalyzer (тяжёлый объект)
_morph: pymorphy3.MorphAnalyzer | None = None


def _get_morph() -> pymorphy3.MorphAnalyzer:
    """Возвращает singleton MorphAnalyzer."""
    global _morph
    if _morph is None:
        _morph = pymorphy3.MorphAnalyzer()
    return _morph


# Маппинг несовершенный → совершенный вид для частых глаголов
# Важно: выбираем форму, которая образует страдательное причастие
_ASPECTUAL_PAIRS: dict[str, str] = {
    # Базовые действия документооборота
    "отправлять": "отправить",
    "получать": "получить",
    "подписывать": "подписать",
    "возвращать": "возвратить",  # НЕ "вернуть" — оно не образует причастие!
    "начислять": "начислить",
    "согласовывать": "согласовать",
    "проверять": "проверить",
    "утверждать": "утвердить",
    "принимать": "принять",
    "отклонять": "отклонить",
    "одобрять": "одобрить",
    "регистрировать": "зарегистрировать",
    "оформлять": "оформить",
    "передавать": "передать",
    "направлять": "направить",
    "рассматривать": "рассмотреть",
    "обрабатывать": "обработать",
    "выполнять": "выполнить",
    "завершать": "завершить",
    "создавать": "создать",
    "формировать": "сформировать",
    "заполнять": "заполнить",
    "присваивать": "присвоить",
    "назначать": "назначить",
    "увольнять": "уволить",
}


def generate_place_name(obj: str, action: str) -> str:
    """
    Генерирует имя Place в форме "<объект> <причастие>".

    Примеры:
        ("заявка", "отправлять") → "заявка отправлена"
        ("договор", "подписывать") → "договор подписан"
        ("премия", "начислять") → "премия начислена"

    Если не удаётся сгенерировать причастие, возвращает fallback.

    Args:
        obj: Объект действия (существительное).
        action: Действие (глагол в инфинитиве).

    Returns:
        Имя состояния в пассивной форме.
    """
    if obj == "-" or not obj:
        return f"действие: {action}"

    morph = _get_morph()

    # 1. Конвертируем несовершенный → совершенный вид
    perfective_verb = _ASPECTUAL_PAIRS.get(action, action)

    # 2. Парсим глагол и объект
    verb_parsed = morph.parse(perfective_verb)[0]
    obj_parsed = morph.parse(obj)[0]

    # 3. Определяем род объекта
    gender = obj_parsed.tag.gender
    if not gender:
        # Fallback для слов без определённого рода
        return f"{obj}: {action}"

    # 4. Генерируем краткое страдательное причастие (PRTS = short passive participle)
    participle = verb_parsed.inflect({"PRTS", "past", "sing", gender})

    if participle:
        return f"{obj} {participle.word}"

    # Fallback: если причастие не сгенерировалось
    return f"{obj}: {action}"
